/** Stable error codes sent by the API, mapped to interface messages. */
const ERROR_CODE_KEYS = {
  nonexistent_time: 'error.nonexistentTime',
  ai_disabled: 'error.aiDisabled',
  household_limit: 'error.aiHouseholdLimit',
  user_limit: 'error.aiUserLimit',
  budget_exhausted: 'error.aiBudget',
  timeout: 'error.aiTimeout',
  provider_error: 'error.aiProvider',
  invalid_output: 'error.aiInvalidOutput',
  refused: 'error.aiRefused',
  interrupted: 'error.aiInterrupted',
  expired: 'error.aiExpired',
} as const satisfies Record<string, MessageKey>;

/** A message in a specific language, e.g. to match a suggested name written in either one. */
export function messageIn(language: Language, key: MessageKey) {
  return language === 'zh' ? zh[key] : en[key];
}

function initialLanguage(): Language {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'en' || stored === 'zh') return stored;
  } catch {
    // Private browsing can make storage unavailable.
  }
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

interface I18nValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: MessageKey, values?: Record<string, string | number>) => string;
  apiError: (error: ApiError) => string;
  /** The translated message for a stable server error code, or null if the code is unknown. */
  errorCode: (code: unknown) => string | null;
}

const Context = createContext<I18nValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setCurrentLanguage] = useState<Language>(initialLanguage);
  useEffect(() => {
    document.documentElement.lang = language === 'zh' ? 'zh-Hans' : 'en';
  }, [language]);
  const setLanguage = (next: Language) => {
    setCurrentLanguage(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // The current selection still works without persistent storage.
    }
  };
  const t: I18nValue['t'] = (key, values) => {
    let value: string = language === 'zh' ? zh[key] : en[key];
    for (const [name, replacement] of Object.entries(values ?? {})) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
    return value;
  };
  const errorCode: I18nValue['errorCode'] = (code) =>
    typeof code === 'string' && Object.hasOwn(ERROR_CODE_KEYS, code)
      ? t(ERROR_CODE_KEYS[code as keyof typeof ERROR_CODE_KEYS])
      : null;
  const apiError: I18nValue['apiError'] = (error) => {
    // English 4xx messages from the server are specific (they can name a time or a limit).
    if (language === 'en' && error.status > 0 && error.status < 500) return error.message;
    const coded = errorCode(error.body?.code);
    if (coded) return coded;
    if (language === 'en') return error.message;
    if (error.status === 0) return t('error.offline');
    if (error.status === 400) return t('error.invalid');
    if (error.status === 401) return t('app.authExpired');
    if (error.status === 403) return t('error.forbidden');
    if (error.status === 404) return t('error.notFound');
    if (error.status === 409) return t('error.conflict');
    if (error.status === 429) return t('error.quota');
    if (error.status >= 500) return t('error.server');
    return t('error.generic');
  };
  return (
    <Context.Provider value={{ language, setLanguage, t, apiError, errorCode }}>
      {children}
    </Context.Provider>
  );
}

export function useI18n(): I18nValue {
  const value = useContext(Context);
  if (!value) throw new Error('LanguageProvider is missing.');
  return value;
}
